// Stage 5.7 salary audit and approval-ready proposal. Reads the live tables and writes
// docs/master/stage5/salary-proposal.md. It changes NO game value: the proposal is
// gated on owner approval (brief: "preserve existing production values until approval").
//   node server/loadtest/salary-proposal.mjs
import fs from 'node:fs';
import * as D from '../src/game/data.js';
import {COURSES, CAREER_REQS, AUTO} from '../src/game/careers.js';

const WEEK_DAYS = c => c.days.length;                 // one paid shift per work day
const RENT_NIMA = D.HOMES.nima.rent;                  // weekly rent, cheapest home
const FOOD_WEEK = 7 * 3 * 15;                         // three cheap meals a day at ~GH₵15
const FARE_WEEK = d => d * 2 * Math.round(D.TRANSPORT.trotro.base + D.TRANSPORT.trotro.perKm * 6);  // 6 km trotro each way
const FLOOR = 80, CEILING_RATIO = 10;                 // proposal parameters

const rows = Object.entries(D.CAREERS).map(([id, c]) => {
  const pays = c.ranks.map(r => r[1]), days = WEEK_DAYS(c);
  const proposed = pays.map((p, i) => i === 0 ? Math.max(FLOOR, p) : Math.max(p, Math.round(Math.max(FLOOR, pays[0]) * (pays[i] / pays[0]))));
  const capped = proposed.map(p => Math.min(p, proposed[0] * CEILING_RATIO));
  const entryCourses = (CAREER_REQS[id]?.[0] || []).map(k => COURSES[k]);
  return {id, name: c.name, days, pays, proposed: capped, entryCost: entryCourses.reduce((n, k) => n + k.cost + (k.requires || []).reduce((m, r) => m + COURSES[r].cost, 0), 0),
    weekly: pays[0] * days, weeklyProposed: capped[0] * days, autoWeekly: Math.round(pays[0] * AUTO.payShare) * days};
});
const living = RENT_NIMA + FOOD_WEEK;
const fmt = n => 'GH₵' + Math.round(n).toLocaleString('en-GH');
let md = `# Stage 5.7 salary audit and proposal (approval required)

Generated by \`server/loadtest/salary-proposal.mjs\` from the live data tables.
**No salary value has been changed.** Production keeps the current table until the owner
approves this proposal.

## Normalised unit

One paid **shift** = one fictional 8-hour shift = one active work session (three
assignments, about 3–4 real minutes) or one auto-shift (${Math.round(AUTO.payShare * 100)}% pay), at most once per
real calendar day on the career's work days. Weekly income = shift pay × work days.

## Cost of living used (cheapest life)

Rent (Nima single room): ${fmt(RENT_NIMA)}/week · food (three ~GH₵15 meals a day): ${fmt(FOOD_WEEK)}/week ·
trotro commute (6 km each way): about ${fmt(FARE_WEEK(6))}/week for six work days.
**Basic living ≈ ${fmt(living)}/week before transport.** Hustler start: GH₵800; Dbee start: GH₵25,000.

## Current entry wages (before) and the proposal (after)

Proposal: entry floor of ${fmt(FLOOR)} per shift so every entry job covers basic living in a
full work week; higher ranks scale proportionally from the new entry wage, never down,
and executive pay is capped at ${CEILING_RATIO}× entry within a career. Courses needed to enter are listed with
their total fees.

| Career | Work days | Entry before | Entry after | Top before | Top after | Weekly entry before | Weekly entry after | Auto weekly (current) | Entry course fees | Covers living (before → after) |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
`;
for (const r of rows) md += `| ${r.name} | ${r.days} | ${fmt(r.pays[0])} | ${fmt(r.proposed[0])} | ${fmt(r.pays[4])} | ${fmt(r.proposed[4])} | ${fmt(r.weekly)} | ${fmt(r.weeklyProposed)} | ${fmt(r.autoWeekly)} | ${fmt(r.entryCost)} | ${r.weekly >= living ? 'yes' : 'no'} → ${r.weeklyProposed >= living ? 'yes' : 'no'} |\n`;
const below = rows.filter(r => r.weekly < living), belowAfter = rows.filter(r => r.weeklyProposed < living);
md += `
## Findings

- ${below.length} of 19 entry jobs pay less than basic living in a full work week today
  (${below.map(r => r.name).join(', ') || 'none'}). After the proposal: ${belowAfter.length} (${belowAfter.map(r => r.name).join(', ') || 'none'}).
  Short-week careers (e.g. Ministry, three days) stay below by design: they suit part-time play.
- Time compression does not change daily income: the once-per-day cap is unchanged, so the
  active-work rate per real day is identical; only the real waiting falls from 60 to ~3–4 minutes.
- Auto-work pays ${Math.round(AUTO.payShare * 100)}% minus the commute, progresses at half speed and catches up at most
  ${AUTO.catchUpDays} offline days, so idle accounts cannot accumulate unbounded income.
- Entry training is free for most careers. The paid routes (Teller ${fmt(COURSES.teller.cost)}, Coding ${fmt(COURSES.codeprac.cost)},
  Teaching ${fmt(COURSES.teach.cost)}, Media ${fmt(COURSES.media.cost)}, Hospital admin ${fmt(COURSES.hospadmin.cost)}, Aviation ${fmt(COURSES.aviation.cost)},
  Leadership ${fmt(COURSES.lead.cost)}) are one-off sinks that a Hustler can reach within one to three weeks of entry work.

## Approval requested

1. Entry wage floor of ${fmt(FLOOR)} per shift with proportional rank scaling (table above).
2. Executive cap of ${CEILING_RATIO}× entry within a career.
Until approved, \`data.js\` keeps today's values. To activate, apply the "after" columns to
\`CAREERS\` ranks in one reviewed change and rerun this report and the economy simulation.
`;
fs.mkdirSync(new URL('../../docs/master/stage5/', import.meta.url), {recursive: true});
fs.writeFileSync(new URL('../../docs/master/stage5/salary-proposal.md', import.meta.url), md);
console.log(`salary proposal written: ${rows.length} careers, ${below.length} below living before, ${belowAfter.length} after`);
